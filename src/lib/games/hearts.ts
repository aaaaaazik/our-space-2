/**
 * Сторона поля: 4×4 клетки.
 *
 * Было 5×5, но двадцать пять клеток на пятерых искать долго: попадание
 * случалось в одном случае из пяти. На шестнадцати клетках попадает
 * каждый четвёртый выстрел, и партия укладывается в один вечер.
 */
export const SIZE = 4;

/** Клеток всего. Нумеруются подряд: строка = idx / SIZE, столбец = idx % SIZE. */
export const CELLS = SIZE * SIZE;

/** Сколько сердец прячет каждый. */
export const HEARTS = 4;

/**
 * Сколько клеток выбирается за один ход.
 *
 * Раньше стреляли по одной, и после каждого выстрела нужно было ждать
 * второго — на поле в шестнадцать клеток это до пятнадцати ожиданий за
 * партию. Залпом по четыре партия укладывается примерно в четыре обмена.
 */
export const SALVO = 4;

