export type Scores = Record<LanguageKey, number>;

export function emptyScores(): Scores {
  return { words: 0, time: 0, gifts: 0, service: 0, touch: 0 };
}

/** answers: номер вопроса → 'a' или 'b'. */
export function scoreAnswers(answers: Record<string, "a" | "b">): Scores {
  const scores = emptyScores();

  for (const [index, choice] of Object.entries(answers)) {
    const pair = LOVE_PAIRS[Number(index)];
    if (!pair) continue;
    scores[pair[choice].key] += 1;
  }

  return scores;
}

/** Языки от самого важного к наименее, с процентами. */
export function ranked(scores: Scores) {
  const total = LANGUAGE_KEYS.reduce((sum, key) => sum + scores[key], 0);

  return LANGUAGE_KEYS.map((key) => ({
    key,
    score: scores[key],
    percent: total > 0 ? Math.round((scores[key] / total) * 100) : 0,
    ...LANGUAGES[key],
  })).sort((a, b) => b.score - a.score);
}
