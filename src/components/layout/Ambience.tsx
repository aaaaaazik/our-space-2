/**
 * Фоновая атмосфера: мягкие световые пятна на тёмной основе.
 *
 * Слой намеренно неподвижен и намеренно один.
 *
 * Раньше пятен было три, каждое своим элементом, и каждое медленно плыло.
 * Пятно шире экрана: телефон держит для него картинку размером больше
 * самого экрана и перерисовывает её, стоит слою сдвинуться. Три такие
 * картинки не помещались в память, которую Safari отводит под слои, и
 * он переставал считать движение на видеокарте — начинал рисовать его
 * обычным способом, наравне со всей остальной страницей. Отсюда и
 * ощущение: плывёт ровно, замирает, потом прыгает в новое место.
 *
 * Теперь это один элемент с тремя градиентами в одной заливке. Он
 * рисуется ровно один раз при открытии страницы и больше не трогается
 * никогда: не движется, а contain: paint отрезает его от остальной
 * страницы, чтобы обновления счётчика и списков его не задевали.
 */
export function Ambience() {
  return (
    <div
      aria-hidden
      className="ambience pointer-events-none fixed inset-0 -z-10"
      style={{
        backgroundImage: [
          // Сверху — сиреневое свечение, самое заметное
          "radial-gradient(circle 68vw at 50% 7%, rgba(168,110,232,0.55) 0%, rgba(168,110,232,0.30) 30%, rgba(168,110,232,0.10) 55%, transparent 75%)",
          // Слева ниже — розовое, чтобы фиолетовый не уходил в холод
          "radial-gradient(circle 50vw at 20% 49%, rgba(238,132,182,0.45) 0%, rgba(238,132,182,0.24) 32%, rgba(238,132,182,0.08) 58%, transparent 76%)",
          // Справа внизу — чтобы низ экрана не проваливался в темноту
          "radial-gradient(circle 46vw at 86% 79%, rgba(140,110,240,0.40) 0%, rgba(140,110,240,0.16) 40%, transparent 72%)",
        ].join(", "),
      }}
    />
  );
}
